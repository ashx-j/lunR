import { readFile, writeFile } from "node:fs/promises";

const release = await readFile(new URL("./computer-use-release.json", import.meta.url), "utf8");
const destination = new URL("../packages/coding-agent/src/core/computer-use/release.generated.ts", import.meta.url);
const content = `// Generated by scripts/generate-computer-use-manifest.mjs.\nexport const computerRelease = ${release.trim()} as const;\n`;
if (process.argv.includes("--check")) {
	if (await readFile(destination, "utf8") !== content) throw new Error("Computer-use generated manifest is stale.");
} else {
	await writeFile(destination, content);
}
